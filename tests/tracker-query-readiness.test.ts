import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile,readdir} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {Service} from '../src/domain/service.js';
import {WorkspaceFoundation} from '../src/workspace/service.js';
import {trackerOperation} from '../src/workspace/tracker-template.js';
import {mergeTrackerSnapshot} from '../src/shared/tracker-cache.js';
import type {Database,Connection} from '../src/db/database.js';

test('full-table ordering, filtering, searching, exact review and draft finalization',async()=>{
 const pg=new PGlite();const db:Database={query:(s,v)=>pg.query(s,v) as any,transaction:f=>pg.transaction(tx=>f(tx as Connection)),close:()=>pg.close()};
 try{
  for(const file of (await readdir('migrations')).filter(f=>f.endsWith('.sql')).sort())await pg.exec(await readFile('migrations/'+file,'utf8'));
  const human={userId:randomUUID(),origin:'human' as const},ai={...human,origin:'ai' as const};
  await db.query('INSERT INTO users(id,subject,email,name) VALUES($1,$2,$3,$4)',[human.userId,human.userId,'query@example.invalid','Query test']);
  const s=new Service(db),f=new WorkspaceFoundation(db),w=await s.createWorkspace(human,'Queries');await s.setAi(human,w.id,true);
  const save=async(operation:any)=>{const p=await s.preview(human,w.id,operation);return s.commit(human,p.id,p.digest,undefined,p.review);};
  const typeId=(await save({kind:'create_type',name:'Companies',fields:[{key:'name',name:'Company',kind:'text',multiple:false,ai:true},{key:'priority',name:'Priority',kind:'select',options:['High','Medium','Low'],multiple:false,ai:true},{key:'score',name:'Score',kind:'number',multiple:false,ai:true}]})).objects[0].id;
  for(let i=0;i<65;i++)await save({kind:'create_record',typeId,data:{name:'Company '+i,priority:i>=30?'High':'Low',...(i===64?{}:{score:i})}});
  const op=await trackerOperation(f,human,w.id,{name:'Priority tracker',description:'',omitSource:true,showExample:false,tabs:[{name:'Companies',typeId,filters:['priority'],columns:[{field:'name'},{field:'priority'},{field:'score'}]}]});
  const p=await f.preview(human,w.id,op),saved=await f.confirm(human,w.id,p.id,p.digest);
  const render=(state:any,event:any)=>f.runFrontend(human,w.id,{componentId:saved.id,expectedVersion:0,state,event});
  let out=await render(null,{kind:'click',action:'tab:0'});
  assert.equal(out.tracker.pages[0].result.total,65);
  out=await render(out.state,{kind:'change',action:'sort',value:'priority'});
  assert.equal(out.state.offsets[0],0);assert.ok(out.tracker.pages[0].result.rows.every((r:any)=>r.data.priority==='High'));
  const page1=out.tracker.pages[0].result.rows;
  out=await render(out.state,{kind:'click',action:'next'});
  assert.equal(out.state.offsets[0],25);assert.equal(out.tracker.pages[0].result.rows.filter((r:any)=>r.data.priority==='High').length,10);
  assert.ok(!out.tracker.pages[0].result.rows.some((r:any)=>page1.some((a:any)=>a.id===r.id)));
  out=await render(out.state,{kind:'click',action:'sort-field:score'});
  assert.equal(out.state.offsets[0],0);assert.equal(out.tracker.pages[0].result.rows[0].data.score,0);
  out=await render(out.state,{kind:'click',action:'sort-field:score'});
  assert.equal(out.tracker.pages[0].result.rows[0].data.score,63);
  out=await render(out.state,{kind:'change',action:'query',value:'Company 60'});
  assert.equal(out.tracker.pages[0].result.total,1);assert.equal(out.tracker.pages[0].result.rows[0].data.score,60);
  out=await render(out.state,{kind:'change',action:'query',value:''});
  out=await render(out.state,{kind:'change',action:'filter:priority',value:'High'});
  assert.equal(out.tracker.pages[0].result.total,35);assert.ok(out.tracker.pages[0].result.rows.every((r:any)=>r.data.priority==='High'));
  await assert.rejects(render(out.state,{kind:'change',action:'sort',value:'unbound'}),/readable bound fields/);
  const change=await s.preview(human,w.id,{kind:'create_record',typeId,data:{name:'Approved'}});
  await assert.rejects(s.commit(human,change.id,change.digest,undefined,'{"kind":"wrong"}'),/do not match/);
  await s.commit(human,change.id,change.digest,undefined,change.review);
  const input={...op,componentId:saved.id,expectedVersion:0};
  const draft=await f.prepareRenderedTracker(ai,w.id,input);
  assert.equal(draft.screen,'tracker');assert.equal(draft.appUpdating,true);assert.equal(draft.component.id,saved.id);assert.equal(draft.preview.reviewState,'draft');
  await assert.rejects(f.confirm(human,w.id,draft.preview.id,draft.preview.digest),/still being prepared/);
  const ready=await f.finalizeAppPreview(ai,w.id,draft.preview.id,draft.preview.digest);
  assert.equal(ready.preview.reviewState,'ready');assert.notEqual(ready.preview.digest,draft.preview.digest);
  await assert.rejects(f.confirm(human,w.id,draft.preview.id,draft.preview.digest),/unavailable/);
  await f.beginAppUpdate(ai,w.id,saved.id,0);
  await assert.rejects(f.confirm(human,w.id,ready.preview.id,ready.preview.digest),/unavailable/);
  const draft2=await f.prepareRenderedTracker(ai,w.id,input);
  const ready2=await f.finalizeAppPreview(ai,w.id,draft2.preview.id,draft2.preview.digest);
  const repeat=await f.finalizeAppPreview(ai,w.id,ready2.preview.id,ready2.preview.digest);assert.equal(repeat.preview.digest,ready2.preview.digest);
  const receipt=await f.confirm(human,w.id,ready2.preview.id,ready2.preview.digest);assert.equal(receipt.id,saved.id);
  assert.equal((await f.readComponent(human,w.id,saved.id)).component.version,1);
 }finally{await pg.close();}
});
test('cache keeps different full-table sorts and searches separate',()=>{
 const output=(sort:any,q='')=>({accessVersion:1,tracker:{config:{},pages:[{request:{typeId:'t',limit:25,offset:0,sort,q},result:{rows:[]}}]}});
 let cache=mergeTrackerSnapshot(null,output(null));
 cache=mergeTrackerSnapshot(cache,output({field:'priority',direction:'asc'}));
 cache=mergeTrackerSnapshot(cache,output({field:'priority',direction:'desc'}));
 cache=mergeTrackerSnapshot(cache,output({field:'priority',direction:'asc'},'target'));
 assert.equal(cache.tracker.pages.length,4);
});
